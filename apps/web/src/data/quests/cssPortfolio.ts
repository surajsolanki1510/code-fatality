type Learn = { tag: string; plain: string; example: string }

type Spec = {
  id: string
  chapter: number
  tier: SkillTier
  kind?: QuestKind
  pack: string
  title: string
  hook: string
  job: string
  learn: Learn[]
  objectives: QuestObjective[]
  hint: string
  html: string
  css: string
  xp?: number
  badgeId?: string
}

function q(s: Spec): QuestDef {
  return {
    id: s.id,
    worldId: 'css-forest',
    speaker: 'Luxe',
    kind: s.kind ?? 'quest',
    tier: s.tier,
    chapter: s.chapter,
    title: s.title,
    hook: s.hook,
    story: [`Portfolio section: ${s.pack}`, s.hook],
    missionBrief: s.job,
    lessonSummary: s.learn.map((l) => l.plain).join(' '),
    tagLessons: s.learn.map((l) => ({ tag: l.tag, purpose: l.plain, example: l.example })),
    objectives: s.objectives,
    hints: [s.hint],
    winQuips: ['Your portfolio just leveled up.', 'Section saved — keep building.', 'That looks hire-ready.'],
    failQuips: ['One checklist item at a time.', 'Peek the example — you got this.', 'Tiny fix, then publish again.'],
    starterHtml: s.html,
    starterCss: s.css,
    xp: s.xp ?? (s.tier === 'expert' ? 90 : s.tier === 'intermediate' ? 70 : 50),
    badgeId: s.badgeId,
  }
}

